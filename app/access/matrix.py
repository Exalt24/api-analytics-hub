"""The access matrix: who may do what to orders, invoices, payments and commissions. ONE table, written once, here.

Everything else reads this table and never retypes it:
  - the API dependency (`requires_access` in app/access/principal.py) looks a cell up before a route body runs;
  - migrations/022_access_matrix.sql holds the same 80 cells as rows of `access_matrix`, generated by `seed_sql()` below (a test fails if the file drifts from this table),
    and the row level security policies read that table at query time through `portal_scope()`;
  - the tests are GENERATED from it: tests/test_access_matrix.py (the API), tests/test_access_matrix_db.py (the database).

A CELL is (role, resource, action) and holds a SCOPE, which says which rows of the resource the role may touch:
    none      nothing: the action is refused
    all       every row of the tenant
    clinic    rows of the clinic the user belongs to (a clinic user, a prescriber)
    assigned  rows of the clinics assigned to the user (a sales rep)
    self      rows that name the user as their sales rep (a rep's own commissions)
A cell that is missing from the table is `none`: the table is closed, so a new role, resource or action grants nothing until it is written here.

ACTIONS. read; create (a new row: an order, a draft invoice, a payment, a commission accrual); update (move a row: an order's status, finalize or void an invoice);
settle (pay an invoice); refund (refund an invoice, reverse a commission). An action a resource has no operation for is `none` for every role (a test checks that).
"""
from __future__ import annotations

from typing import Iterator

ROLES = ("clinic", "prescriber", "sales_rep", "admin")
RESOURCES = ("orders", "invoices", "payments", "commissions")
ACTIONS = ("read", "create", "update", "settle", "refund")
SCOPES = ("none", "clinic", "assigned", "self", "all")

#: role -> resource -> action -> scope. Anything not written is "none".
_GRANTS: dict[str, dict[str, dict[str, str]]] = {
    "clinic": {
        "orders": {"read": "clinic", "create": "clinic", "update": "clinic"},
        "invoices": {"read": "clinic", "settle": "clinic"},
        "payments": {"read": "clinic", "create": "clinic"},
    },
    "prescriber": {
        "orders": {"read": "clinic", "create": "clinic", "update": "clinic"},
    },
    "sales_rep": {
        "orders": {"read": "assigned"},
        "invoices": {"read": "assigned"},
        "payments": {"read": "assigned"},
        "commissions": {"read": "self"},
    },
    "admin": {
        "orders": {"read": "all", "create": "all", "update": "all"},
        "invoices": {"read": "all", "create": "all", "update": "all", "settle": "all", "refund": "all"},
        "payments": {"read": "all", "create": "all", "update": "all"},
        "commissions": {"read": "all", "create": "all", "refund": "all"},
    },
}


def cells() -> Iterator[tuple[str, str, str]]:
    """Every (role, resource, action), in a fixed order: ROLES x RESOURCES x ACTIONS."""
    for role in ROLES:
        for resource in RESOURCES:
            for action in ACTIONS:
                yield role, resource, action


def scope(role: str, resource: str, action: str) -> str:
    """The cell's scope. An unknown role, resource or action is `none`, never an error that a caller could turn into an allow."""
    return _GRANTS.get(role, {}).get(resource, {}).get(action, "none")


def allows(role: str, resource: str, action: str) -> bool:
    return scope(role, resource, action) != "none"


def validate() -> None:
    """The table names only known roles, resources, actions and scopes. Run by the tests and at import time of the seed."""
    for role, by_resource in _GRANTS.items():
        assert role in ROLES, role
        for resource, by_action in by_resource.items():
            assert resource in RESOURCES, resource
            for action, sc in by_action.items():
                assert action in ACTIONS and sc in SCOPES and sc != "none", (role, resource, action, sc)


def seed_sql() -> str:
    """The rows of `access_matrix`, one for each cell (explicit `none` rows included, so the database table is as complete as this one)."""
    validate()
    rows = ["    ('%s', '%s', '%s', '%s')" % (r, res, act, scope(r, res, act)) for r, res, act in cells()]
    return ("insert into access_matrix (role, resource, action, scope) values\n" + ",\n".join(rows) +
            "\non conflict (role, resource, action) do update set scope = excluded.scope;")
